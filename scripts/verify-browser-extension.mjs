import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const read = (path) => readFileSync(new URL(path, import.meta.url), "utf8");
const manifest = JSON.parse(read("../browser-extension/manifest.json"));
const popup = read("../browser-extension/popup.js");
const content = read("../browser-extension/content.js");
const worker = read("../browser-extension/background.js");
const readme = read("../browser-extension/README.md");
assert.equal(manifest.manifest_version, 3);
assert.deepEqual([...manifest.permissions].sort(), ["activeTab","scripting","storage"]);
assert.equal(manifest.host_permissions, undefined);
assert.equal(manifest.content_scripts, undefined);
assert.equal(manifest.background.service_worker, "background.js");
assert.match(popup, /select-target/);
assert.match(content, /KYVORIX_APP_REQUEST/);
assert.match(content, /KYVORIX_TARGET_ACTION/);
assert.match(worker, /KYVORIX_REGISTER_TARGET_TAB/);
assert.match(worker, /KYVORIX_REGISTER_APP_TAB/);
assert.match(worker, /sender\.tab\?\.id/);
assert.match(worker, /chrome\.storage\.session/);
assert.match(worker, /saved\[APP_TAB_KEY\]/);
assert.match(content, /action === "read"/);
assert.match(content, /action === "click"/);
assert.match(content, /action === "fill"/);
assert.match(content, /password/);
assert.doesNotMatch(content, /\.submit\s*\(|requestSubmit\s*\(/);
assert.doesNotMatch(worker, /cookies/);
assert.match(readme, /select.*website tab/i);
console.log("Browser extension cross-tab bridge and security checks passed.");
